import type { FactionId, PatronId, ProductId } from "./types";

export interface PatronKind {
  id: PatronId;
  faction: FactionId;
  name: string;
  role: string;
  blurb: string;
  purse: number;
  binge: number;
  favorite: ProductId;
  hue: number;
}

const HUES = [0, 28, 52, 88, 128, 168, 208, 248, 292, 328];

function pack(
  faction: FactionId,
  rows: [string, string, string, number, number, ProductId][],
): PatronKind[] {
  return rows.map((row, i) => ({
    id: `${faction}-${i}` as PatronId,
    faction,
    name: row[0],
    role: row[1],
    blurb: row[2],
    purse: row[3],
    binge: row[4],
    favorite: row[5],
    hue: HUES[i] ?? i * 36,
  }));
}

